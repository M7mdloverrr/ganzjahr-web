import 'package:flutter/widgets.dart';

enum AppLang { en, de, ar }

extension AppLangInfo on AppLang {
  String get nativeName => switch (this) {
    AppLang.en => 'English',
    AppLang.de => 'Deutsch',
    AppLang.ar => 'العربية',
  };
  Locale get locale => Locale(name);
}

AppLang appLang = AppLang.en;

AppLang langFromCode(String? code) => AppLang.values.firstWhere((l) => l.name == code, orElse: () => AppLang.en);

extension Tr on String {
  String get tr => switch (appLang) {
    AppLang.en => this,
    AppLang.de => _de[this] ?? this,
    AppLang.ar => _ar[this] ?? this,
  };

  /// Translates a template like 'Year {year}' and fills in the placeholders.
  String trf(Map<String, Object> args) {
    var s = tr;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }
}

